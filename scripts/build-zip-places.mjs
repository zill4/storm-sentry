// Regenerates src/lib/zips/data/zip-places.ts from the `zipcodes` npm package
// (MIT-licensed US ZIP → city/state data). Run once when refreshing:
//
//   node scripts/build-zip-places.mjs
//
// It emits a compact packed string ("zip,City Name,ST;…") consumed by
// src/lib/zips/places.ts for city/state labels and city/state search. The data
// module is server-only (never imported by client components) so its size
// never reaches the browser bundle.
import { writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const require = createRequire(import.meta.url)
// The package exports { codes, stateMap }; codes: zip → { zip, city, state, country, … }
const { codes } = require("zipcodes/lib/codes.js")

const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "lib",
  "zips",
  "data",
  "zip-places.ts",
)

const rows = []
for (const key of Object.keys(codes)) {
  const e = codes[key]
  if (!e || typeof e !== "object") continue
  const zip = String(e.zip ?? key)
  if (!/^\d{5}$/.test(zip)) continue // US 5-digit only (skips CA postal codes)
  if (e.country && e.country !== "US") continue
  const city = String(e.city ?? "").replace(/[;,]/g, " ").trim()
  const state = String(e.state ?? "").trim()
  if (!city || !/^[A-Z]{2}$/.test(state)) continue
  rows.push(`${zip},${city},${state}`)
}
rows.sort()

const header = `// AUTO-GENERATED by scripts/build-zip-places.mjs from the \`zipcodes\` npm
// package (MIT). Do not edit by hand — rerun the script to refresh.
// Format: semicolon-separated rows of "zip,City Name,ST". ${rows.length} ZIPs.
/* eslint-disable */
export const ZIP_PLACES_PACKED =
`

writeFileSync(OUT, `${header}  ${JSON.stringify(rows.join(";"))}\n`)
console.log(`Wrote ${OUT} (${rows.length} zips)`)
